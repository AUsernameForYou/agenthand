"""agenthand MCP server (stdio transport).

Three production tools for AI agents that help people sell, in the order
a listing is actually produced:

  draw(asset, scene_prompt)  -> the REAL product placed into a generated
                                scene, under the Fidelity Lock, with its
                                fidelity receipt
  cut_out(image, concept?)   -> the product, cut out, as a transparent PNG
  identify(image)            -> the planning step inside the chain: reads
                                a photo and plans the cut (the noun-phrase
                                concept and alternates cut_out will use)

FIDELITY LOCK (the core design invariant of draw):
  The product layer is NEVER regenerated by a model. Segmentation extracts
  the real foreground; that layer is stored untouched and its hashes (file
  bytes and decoded pixels) are recorded in the asset store. The image
  model generates ONLY the background scene plate, from a prompt and
  dimensions — it never receives product pixels. Deterministic code
  composites the stored product layer onto the plate, which is resized to
  the product, never the reverse. The returned fidelity receipt carries
  the source, foreground, and mask hashes plus the measured count of
  changed opaque foreground pixels (must be 0) and the edge-band count,
  so a caller can verify this precise claim: the stored extracted
  foreground reached the composite unchanged. Any change to this module
  must preserve that invariant: if a code path regenerates product pixels
  with a model, it is a bug, not a feature.

Billing: every billable call goes through meta_client.billed_call
(reserve-then-settle under the fail-closed spend cap). Tools never touch
the ledger directly.

Status: draw's compositing pipeline runs locally end to end today with a
deterministic placeholder plate (the background model is not wired yet,
so no external call is made). identify IS wired to the real vision model
(muse-spark-1.3) through the billing choke point: it returns the plan
plus listing copy, or a structured error (NOT_CONFIGURED when no
META_API_KEY is set — checked before any billing, so no ledger write;
BAD_MODEL_RESPONSE when the model's answer is unusable — the billed
reservation stays counted; an unparseable body is saved raw under
data/debug/ and its path rides in the error). cut_out's segmentation model is not wired
yet; it exercises the ingest, planning, and billing plumbing and returns
a structured "not yet wired" result.
"""

from __future__ import annotations

from mcp.server.mcpserver import Image, MCPServer

from . import composite, config, ingest, meta_client
from .assets import HANDLE_PREFIX, AssetStore

# mcp Python SDK v2: the high-level server class is MCPServer
# (renamed from FastMCP in v1).
mcp = MCPServer("agenthand")

# Model assignments (priced in pricing.py). identify starts on Spark; a
# Spark-vs-Wonder A/B during the build decides whether it stays there.
IDENTIFY_MODEL = "muse-spark-1.3"
CUT_OUT_MODEL = "sam-3.1"
DRAW_BACKGROUND_MODEL = "muse-image-1.0"

STUB_NOTE = "Stub: model not wired yet; no external call was made."


def _store() -> AssetStore:
    return AssetStore(config.get_data_dir())


@mcp.resource("asset://{asset_id}", mime_type="image/png")
def asset_resource(asset_id: str) -> bytes:
    """Read a stored asset back by id — the egress half of the handle system.

    Any asset a tool returns as asset://<id> can be fetched by the client
    as the MCP resource at the same URI.
    """
    return _store().read_bytes(HANDLE_PREFIX + asset_id)


@mcp.tool()
def draw(asset: str, scene_prompt: str) -> list:
    """Stage the real product into a generated scene. Fidelity Lock applies.

    Args:
        asset: Asset handle (asset://<id>) of the cut-out product layer
            produced by cut_out (kind foreground_png, chained to a source
            photo). Anything else is refused.
        scene_prompt: Description of the scene to generate around the
            product, e.g. "a regal, warmly lit reading room".

    The product layer is composited onto the background plate exactly as
    stored; it is never regenerated, restyled, scaled, or "improved" by a
    model. Returns the composite's asset handle, its fidelity receipt
    (source/foreground/mask file and pixel hashes, transformations,
    changed opaque pixel count, edge-band count), and an image preview of
    the composite.

    Today the plate is a deterministic local placeholder (the background
    model is not wired yet); the compositing, lineage checks, and receipt
    are the real pipeline.
    """
    store = _store()
    # Validate (kind, lineage, integrity) BEFORE billing: a refused asset
    # never reaches the gate and never leaves a reservation behind.
    composite.validate_foreground(store, asset)
    outcome: dict = {}

    def _run_composite() -> dict:
        handle, receipt = composite.draw_product(store, asset, scene_prompt)
        outcome["handle"] = handle
        outcome["receipt"] = receipt
        return {}  # no model usage yet: the plate is a local placeholder

    billing = meta_client.billed_call(
        "draw",
        DRAW_BACKGROUND_MODEL,
        0.0,
        _run_composite,
        status="stub",
        note="Local placeholder plate; background model not wired yet.",
    )
    result = {
        "status": "ok",
        "tool": "draw",
        "asset": asset,
        "scene_prompt": scene_prompt,
        "output_asset": outcome["handle"],
        "fidelity_receipt": outcome["receipt"],
        "model": DRAW_BACKGROUND_MODEL,
        "cost_usd": billing["actual_usd"],
        "note": (
            "Composite produced by the real Fidelity Lock pipeline with a "
            "deterministic local placeholder plate; the muse-image "
            "background model is not wired yet, so no API call was made."
        ),
    }
    preview = Image(data=store.read_bytes(outcome["handle"]), format="png")
    return [result, preview]


@mcp.tool()
def cut_out(image: str, concept: str | None = None) -> dict:
    """Cut the product out of its photo as a transparent PNG.

    Args:
        image: The product photo — an asset handle (asset://<id>), an
            http(s) URL, or a base64 data URI. It is ingested and
            normalized first.
        concept: Optional noun-phrase concept naming what to segment
            ("brown leather wallet"). When omitted, the identify planning
            step runs internally to produce the concept and alternates.

    Wired behavior: the segmentation model returns a mask for the concept;
    the mask is quality-checked (a bounded recovery loop retries once with
    an alternate concept phrase on a poor mask, traced in the receipt);
    the extracted foreground is stored untouched in the asset store with
    its hashes recorded, and the new asset handle is returned.
    """
    store = _store()
    handle = ingest.ingest(image, store)
    concept_source = "provided"
    alternates: list[str] = []
    plan_error = None
    if concept is None:
        plan = _plan_cut(store, handle)
        concept = plan["concept"]
        alternates = plan["alternates"]
        plan_error = plan.get("error")
        concept_source = "identify_internal"
    meta_client.billed_call(
        "cut_out",
        CUT_OUT_MODEL,
        0.0,
        lambda: {},
        status="stub",
        note=STUB_NOTE,
    )
    return {
        "status": "not_yet_wired",
        "tool": "cut_out",
        "image": handle,
        "concept": concept,
        "concept_source": concept_source,
        "alternates": alternates,
        "plan_error": plan_error,
        "output_asset": None,
        "mask_asset": None,
        "model": CUT_OUT_MODEL,
        "note": STUB_NOTE,
    }


def _run_identify(store: AssetStore, handle: str) -> dict:
    """Run the real identify planning step for a stored photo.

    On success returns the plan (description, concept, alternates,
    listing fields) plus cost_usd, usage, and call_id from the settled
    receipt. Expected failures return {"error": {...}} instead of
    raising:

    - NOT_CONFIGURED: no META_API_KEY. Checked before billed_call runs,
      so nothing is written to the ledger for a setup problem.
    - BAD_MODEL_RESPONSE: the model's response was unusable. The call
      went through the choke point and its reservation stays counted as
      spend; cost_counted_usd reports the reserved amount. When the body
      was unparseable, its full raw text was saved under data/debug/
      and debug_path points at that file.

    SpendCapExceeded propagates: an exhausted budget refuses loudly
    rather than degrading into an empty plan.
    """
    try:
        meta_client.require_meta_api_key()
    except meta_client.NotConfiguredError as exc:
        return {"error": {"code": "NOT_CONFIGURED", "message": str(exc)}}

    record = store.get_record(handle)
    store.verify_integrity(handle)
    png_bytes = store.read_bytes(handle)
    projected = meta_client.project_identify_cost_usd(
        IDENTIFY_MODEL, record.width, record.height
    )
    outcome: dict = {}

    def _call() -> dict:
        plan, usage = meta_client.vision_identify(png_bytes, model=IDENTIFY_MODEL)
        outcome["plan"] = plan
        return usage

    try:
        billing = meta_client.billed_call(
            "identify", IDENTIFY_MODEL, projected, _call
        )
    except meta_client.IdentifyResultError as exc:
        error = {
            "code": "BAD_MODEL_RESPONSE",
            "message": str(exc),
            "cost_counted_usd": projected,
        }
        if getattr(exc, "debug_path", None):
            error["debug_path"] = exc.debug_path
        return {"error": error}
    plan = dict(outcome["plan"])
    plan["model"] = IDENTIFY_MODEL
    plan["cost_usd"] = billing["actual_usd"]
    plan["usage"] = billing["usage"]
    plan["call_id"] = billing["call_id"]
    return plan


def _plan_cut(store: AssetStore, handle: str) -> dict:
    """The identify planning step, as shared internal logic.

    cut_out calls this when no concept is supplied, so the plan is
    produced inside the chain instead of by a separate tool call. An
    expected identify failure (not configured, unusable response)
    degrades to an empty plan with the error attached: cut_out's own
    segmentation step is still stubbed, so the chain reports the
    planning gap in its result instead of crashing.
    """
    result = _run_identify(store, handle)
    if "error" in result:
        return {
            "description": None,
            "concept": None,
            "alternates": [],
            "model": IDENTIFY_MODEL,
            "error": result["error"],
        }
    return result


@mcp.tool()
def identify(image: str) -> dict:
    """Plan the cut for a product photo (step inside the listing chain).

    Args:
        image: The product photo — an asset handle (asset://<id>), an
            http(s) URL, or a base64 data URI. It is ingested and
            normalized first.

    Reads the photo with the vision model and returns the plan the
    chain consumes: a structured description, the noun-phrase concept
    suitable for text-prompted segmentation ("brown leather wallet")
    with at least two alternate phrasings the mask-recovery loop can
    retry with, plus listing copy (suggested_title, listing_bullets,
    condition_notes). The call is billed through the spend-cap choke
    point and the result carries its actual cost and token usage.

    Without META_API_KEY configured the tool returns a structured
    NOT_CONFIGURED error and makes no call (and no ledger entry). This
    tool exists to serve the chain; the sellable outputs are cut_out's
    transparent PNG and draw's staged composite with its fidelity
    receipt.
    """
    store = _store()
    handle = ingest.ingest(image, store)
    result = _run_identify(store, handle)
    if "error" in result:
        return {
            "status": "error",
            "tool": "identify",
            "image": handle,
            "description": None,
            "concept": None,
            "alternates": [],
            "suggested_title": None,
            "listing_bullets": [],
            "condition_notes": None,
            "model": IDENTIFY_MODEL,
            "error": result["error"],
        }
    return {
        "status": "ok",
        "tool": "identify",
        "image": handle,
        "description": result["description"],
        "concept": result["concept"],
        "alternates": result["alternates"],
        "suggested_title": result["suggested_title"],
        "listing_bullets": result["listing_bullets"],
        "condition_notes": result["condition_notes"],
        "model": IDENTIFY_MODEL,
        "cost_usd": result["cost_usd"],
        "usage": result["usage"],
        "call_id": result["call_id"],
    }


def main() -> None:
    # Make sure the data dir exists so the first receipt write cannot fail
    # on a missing directory; the store and ledger create their own files.
    store = AssetStore(config.get_data_dir())
    store.assets_dir.mkdir(parents=True, exist_ok=True)
    mcp.run(transport="stdio")


if __name__ == "__main__":
    main()
