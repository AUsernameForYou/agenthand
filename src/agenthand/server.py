def _persist_full_receipt(
    store: AssetStore,
    handle: str,
    receipt: dict,
    billing: dict,
    scene_prompt: str,
    scene_guard: dict,
    plate_metrics: dict | None = None,
) -> dict:
    """Enrich the persisted fidelity receipt with run attribution.

    composite.draw_product persists the receipt it computes (hashes,
    counts, the published excluded set, colour-profile fields) beside
    the composite as ``<asset_id>.receipt.json``. Billing settles in
    this layer, so the cost and call attribution only exist here:
    they are merged into that same file, leaving every fidelity field
    exactly as the compositor wrote it. Returns the full persisted
    receipt dict.
    """
    full = dict(receipt)
    full.update(
        {
            "tool": "draw",
            "model": DRAW_BACKGROUND_MODEL,
            "scene_prompt": scene_prompt,
            "scene_guard": scene_guard,
            "cost_usd": billing["actual_usd"],
            "usage": billing.get("usage"),
            "call_id": billing.get("call_id"),
            "call_ids": billing.get("call_ids", [billing.get("call_id")]),
        }
    )
    if plate_metrics is not None:
        full["plate_metrics"] = plate_metrics
    store.save_receipt(handle, full)
    return full


def _measure_plate_metrics(store: AssetStore, source_handle: str) -> dict:
    """The cut-time plate measurement (decision 152): one billed
    Muse Spark vision read of the source photo. Never fatal: any
    failure (no key, transport, unusable answer) records the
    measurement as unavailable with the reason, and the cut
    proceeds with every field an explicit unknown.

    Returns the cut-result record; the mask chunk carries
    {"status", **fields} from the same record.
    """
    base = {
        "source": "vision",
        "model": IDENTIFY_MODEL,
        "rule": platemetrics.RULE,
    }
    try:
        record = store.get_record(source_handle)
        png_bytes = store.read_bytes(source_handle)
        projected = meta_client.project_metrics_cost_usd(
            IDENTIFY_MODEL, record.width, record.height
        )
    except Exception as exc:  # noqa: BLE001 - the record states the reason
        return {
            **base,
            "status": "unavailable",
            "fields": platemetrics.PlateMetrics.unknown().to_json(),
            "reason": str(exc),
        }
    outcome: dict = {}

    def _call() -> dict:
        metrics, usage = meta_client.vision_plate_metrics(
            png_bytes, model=IDENTIFY_MODEL
        )
        outcome["metrics"] = metrics
        return usage

    try:
        billing = meta_client.billed_call(
            "cut_out",
            IDENTIFY_MODEL,
            projected,
            _call,
            note="plate metrics vision read (decision 152)",
        )
    except Exception as exc:  # noqa: BLE001 - the record states the reason
        return {
            **base,
            "status": "unavailable",
            "fields": platemetrics.PlateMetrics.unknown().to_json(),
            "reason": str(exc),
        }
    return {
        **base,
        "status": "measured",
        "fields": outcome["metrics"].to_json(),
        "cost_usd": billing["actual_usd"],
        "call_id": billing["call_id"],
    }


def _plate_metrics_draw_record(
    stored,
    status: str,
    conflicts: list,
    gate_status: str,
    gate_attempts: list,
    gate_reason: str | None,
    grounding: dict,
    placement_json: dict | None,
) -> dict:
    """The `plate_metrics` record persisted on the draw receipt and
    mirrored onto the tool result (decision 152): the stored
    measurement, the clauses it composed (enforced draws only), the
    scene phrases it overrode, and the gate's outcome as it stands.
    """
    gate = {"status": gate_status, "attempts": gate_attempts}
    if gate_reason is not None:
        gate["reason"] = gate_reason
    record = {
        "status": status,
        "measured": stored[0].to_json() if stored else None,
        "gate": gate,
        "grounding": grounding,
        "rule": platemetrics.RULE,
    }
    if placement_json is not None:
        record["placement"] = placement_json
    if status == "enforced" and stored:
        record["clauses"] = platemetrics.clauses_for(stored[0]).to_json()
        record["overridden_scene_phrases"] = conflicts
    return record


def _run_plate_gate(store: AssetStore, composite_handle: str) -> tuple:
    """One gate read: the plate-metrics measurement of a finished
    composite, billed through the choke point (decision 152).
    Returns ("observed", metrics, cost_usd, call_id), or
    ("unavailable", reason) — a read that cannot run is recorded
    by the caller as unverified, never as passed.
    """
    try:
        meta_client.require_meta_api_key()
        record = store.get_record(composite_handle)
        png_bytes = store.read_bytes(composite_handle)
        projected = meta_client.project_metrics_cost_usd(
            IDENTIFY_MODEL, record.width, record.height
        )
    except Exception as exc:  # noqa: BLE001 - the record states the reason
        return ("unavailable", str(exc))
    outcome: dict = {}

    def _call() -> dict:
        metrics, usage = meta_client.vision_plate_metrics(
            png_bytes, model=IDENTIFY_MODEL
        )
        outcome["metrics"] = metrics
        return usage

    try:
        billing = meta_client.billed_call(
            "draw",
            IDENTIFY_MODEL,
            projected,
            _call,
            note="plate geometry gate read (decision 152)",
        )
    except Exception as exc:  # noqa: BLE001 - the record states the reason
        return ("unavailable", str(exc))
    return ("observed", outcome["metrics"], billing["actual_usd"], billing["call_id"])


VERIFY_URL_BASE = "https://ausernameforyou.github.io/agenthand/verify"


def _canonical_receipt_json(receipt: dict) -> str:
    """Canonical receipt JSON for hashing: sorted keys, compact
    separators, unescaped UTF-8 — byte-identical to the Rust
    build's serde_json serialization of the same receipt data and
    to the docs verifier's JS canonicalization."""
    return json.dumps(
        receipt, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    )


def _annotate_verify_fields(store: AssetStore, handle: str, full: dict) -> dict:
    """AB 723 verify annotation, mirroring the Rust build: hash the
    full persisted receipt BEFORE annotation, derive its verify
    URL, persist the field, and return the result-level fields
    (verify_url + the ready-to-paste label line). Older receipts
    without the field still verify; stripping the field and
    re-canonicalizing reproduces the hash in the URL.

    Divergence (recorded 2026-10-31): the QR PNG sidecar itself
    (qr_asset / qr_sha256) is rendered by the Rust build only —
    this environment has no QR library — so Python results carry
    the URL and label but no QR asset."""
    digest = hashlib.sha256(_canonical_receipt_json(full).encode("utf-8")).hexdigest()
    verify_url = f"{VERIFY_URL_BASE}#{digest}"
    annotated = dict(full)
    annotated["verify_url"] = verify_url
    store.save_receipt(handle, annotated)
    fields = {
        "verify_url": verify_url,
        "label": f"Digitally altered. Original photo and proof: {verify_url}",
    }
    # Provenance signals (mirrors the Rust build): mirror the
    # block the receipt carries onto the tool result, with the
    # location warning as its own field.
    block = full.get("provenance")
    if isinstance(block, dict):
        fields["provenance"] = block
        warning = block.get("location_warning")
        if warning:
            fields["location_warning"] = warning
    return fields


