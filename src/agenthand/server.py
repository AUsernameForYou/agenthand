"""agenthand MCP server (stdio transport).

Three production tools for AI agents that help people sell, in the order
a listing is actually produced:

  draw(asset, scene_prompt)  -> the REAL product placed into a generated
                                scene, under the Fidelity Lock, with its
                                fidelity receipt
  cut_out(image, concept?)   -> the product, cut out, as a transparent PNG
  identify(image)            -> the planning step inside the chain: reads
                                a photo and plans the cut (the noun-phrase
                                concept and alternates cut_out will use)

FIDELITY LOCK (the core design invariant of draw):
  The product layer is NEVER regenerated by a model. Segmentation extracts
  the real foreground; that layer is stored untouched and its hashes (file
  bytes and decoded pixels) are recorded in the asset store. The image
  model generates ONLY the background scene plate, from a prompt and
  dimensions — it never receives product pixels. Deterministic code
  composites the stored product layer onto the plate, which is resized to
  the product, never the reverse. The returned fidelity receipt carries
  the source, foreground, and mask hashes plus the measured count of
  changed opaque foreground pixels (must be 0), the edge-band count and
  its maximum width, the mask's total footprint and opaque share, and
  the colour-profile identity of the source photo and the composite
  (color_profile_preserved must be true: a dropped or changed ICC
  profile recolours the product while pixel values stay identical, so
  it is a fidelity failure on the same footing as a changed pixel). A
  caller can verify this precise claim: the stored extracted foreground
  reached the composite unchanged. The receipt is not the only grader:
  composite.verify_receipt_from_disk re-derives every number from the
  stored files, and the standalone agenthand-verify checker verifies
  exported files with no store at all. Any change to this module must
  preserve that invariant: if a code path regenerates product pixels
  with a model, it is a bug, not a feature.

Billing: every billable call goes through meta_client.billed_call
(reserve-then-settle under the fail-closed spend cap). Tools never touch
the ledger directly.

Status: identify IS wired to the real vision model (muse-spark-1.3)
through the billing choke point: it returns the plan plus listing copy,
or a structured error (NOT_CONFIGURED when no META_API_KEY is set —
checked before any billing, so no ledger write; BAD_MODEL_RESPONSE when
the model's answer is unusable — the billed reservation stays counted;
an unparseable body is saved raw under data/debug/ and its path rides
in the error). cut_out IS wired to the real segmentation model
(sam-3.1) through the same choke point: it returns the transparent
foreground and mask handles with their hashes and the attempt trace, or
a structured error (NOT_CONFIGURED, NO_MATCH, POOR_MASK,
BAD_MODEL_RESPONSE) with the attempts' spend counted. draw IS wired to
the real image model (muse-image-1.0) through the same choke point:
the model generates ONLY the empty background plate (stored as a
background_plate asset, pinned in the fidelity receipt), deterministic
code composites the stored product layer onto it, and a measured
changed-opaque-pixel count other than zero — or a colour profile that
did not survive from the source photo to the composite — turns the
result into a FIDELITY_VIOLATION error rather than a false receipt.
Plate failures
return IMAGE_REFUSED / BAD_IMAGE_RESPONSE / IMAGE_CALL_FAILED with the
reservation counted. The deterministic placeholder plate survives ONLY
behind the explicit AGENTHAND_DRAW_PLACEHOLDER_PLATE dev flag, for
offline tests and no-key demos; live mode never substitutes it.
"""

