"""agenthand MCP server (stdio transport).

Three production tools for AI agents that help people sell, in the order
a listing is actually produced:

  draw(asset, scene_prompt)  -> the REAL product placed into a generated
                                scene, under the Fidelity Lock, with its
                                fidelity receipt
  cut_out(image, concept?)   -> the product, cut out, as a transparent PNG
  identify(image)            -> the planning step inside the chain: reads
                                a photo and plans the cut (the noun-phrase
                                concept and alternates cut_out will use)

FIDELITY LOCK (the core design invariant of draw):
  The product layer is NEVER regenerated by a model. Segmentation extracts
  the real foreground; that layer is stored untouched and its hashes (file
  bytes and decoded pixels) are recorded in the asset store. The image
  model generates ONLY the background scene plate, from a prompt and
  dimensions — it never receives product pixels. Deterministic code
  composites the stored product layer onto the plate, which is resized to
  the product, never the reverse. The returned fidelity receipt carries
  the source, foreground, and mask hashes plus the measured count of
  changed opaque foreground pixels (must be 0) and the edge-band count,
  so a caller can verify this precise claim: the stored extracted
  foreground reached the composite unchanged. Any change to this module
  must preserve that invariant: if a code path regenerates product pixels
  with a model, it is a bug, not a feature.

Billing: every billable call goes through meta_client.billed_call
(reserve-then-settle under the fail-closed spend cap). Tools never touch
the ledger directly.

Status: identify IS wired to the real vision model (muse-spark-1.3)
through the billing choke point: it returns the plan plus listing copy,
or a structured error (NOT_CONFIGURED when no META_API_KEY is set —
checked before any billing, so no ledger write; BAD_MODEL_RESPONSE when
the model's answer is unusable — the billed reservation stays counted;
an unparseable body is saved raw under data/debug/ and its path rides
in the error). cut_out IS wired to the real segmentation model
(sam-3.1) through the same choke point: it returns the transparent
foreground and mask handles with their hashes and the attempt trace, or
a structured error (NOT_CONFIGURED, NO_MATCH, POOR_MASK,
BAD_MODEL_RESPONSE) with the attempts' spend counted. draw IS wired to
the real image model (muse-image-1.0) through the same choke point:
the model generates ONLY the empty background plate (stored as a
background_plate asset, pinned in the fidelity receipt), deterministic
code composites the stored product layer onto it, and a measured
changed-opaque-pixel count other than zero turns the result into a
FIDELITY_VIOLATION error rather than a false receipt. Plate failures
return IMAGE_REFUSED / BAD_IMAGE_RESPONSE / IMAGE_CALL_FAILED with the
reservation counted. The deterministic placeholder plate survives ONLY
behind the explicit AGENTHAND_DRAW_PLACEHOLDER_PLATE dev flag, for
offline tests and no-key demos; live mode never substitutes it.
"""

from __future__ import annotations

from io import BytesIO

from mcp.server.mcpserver import Image, MCPServer

from . import composite, config, ingest, meta_client, segmentation
from .assets import HANDLE_PREFIX, KIND_FOREGROUND, KIND_MASK, AssetStore

# mcp Python SDK v2: the high-level server class is MCPServer
# (renamed from FastMCP in v1).
mcp = MCPServer("agenthand")

# Model assignments (priced in pricing.py). identify starts on Spark; a
# Spark-vs-Wonder A/B during the build decides whether it stays there.
IDENTIFY_MODEL = "muse-spark-1.3"
CUT_OUT_MODEL = "sam-3.1"
DRAW_BACKGROUND_MODEL = "muse-image-1.0"


def _store() -> AssetStore:
    return AssetStore(config.get_data_dir())


@mcp.resource("asset://{asset_id}", mime_type="image/png")
def asset_resource(asset_id: str) -> bytes:
    """Read a stored asset back by id — the egress half of the handle system.

    Any asset a tool returns as asset://<id> can be fetched by the client
    as the MCP resource at the same URI.
    """
    return _store().read_bytes(HANDLE_PREFIX + asset_id)


@mcp.tool()
def draw(asset: str, scene_prompt: str) -> list | dict:
    """Stage the real product into a generated scene. Fidelity Lock applies.

    Args:
        asset: Asset handle (asset://<id>) of the cut-out product layer
            produced by cut_out (kind foreground_png, chained to a source
            photo). Anything else is refused before any billing.
        scene_prompt: Description of the scene to generate around the
            product, e.g. "a regal, warmly lit reading room". The words
            are wrapped in a fixed instruction asking the image model
            for an EMPTY scene with a clear central surface, so what
            comes back is a stage, not a picture of a product.

    The background plate is generated by muse-image-1.0 (billed through
    the spend-cap choke point at the per-image rate) and stored as a
    background_plate asset; deterministic code then fits the PLATE to
    the product's dimensions and composites the stored product layer
    onto it. The product layer is never regenerated, restyled, scaled,
    or "improved" by a model, and it is never sent to the image model.
    Returns the composite's asset handle, its fidelity receipt (source /
    foreground / mask / plate hashes, transformations, the measured
    changed-opaque-pixel count), and an image preview. If the compositor
    ever measured changed opaque pixels, the tool returns a
    FIDELITY_VIOLATION error instead of presenting the composite under a
    false receipt.

    Failures return a structured error: NOT_CONFIGURED (no
    META_API_KEY; checked before billing, so no ledger write),
    IMAGE_REFUSED / BAD_IMAGE_RESPONSE / IMAGE_CALL_FAILED (the plate
    call failed; its reservation stays counted as spend). A failed draw
    never falls back to regenerating the product, and in live mode it
    never silently substitutes the placeholder plate.

    Offline dev mode: with AGENTHAND_DRAW_PLACEHOLDER_PLATE=1 the plate
    is the deterministic local placeholder and no API call is made. That
    flag exists for tests and no-key demos only.
    """
    store = _store()
    # Validate (kind, lineage, integrity) BEFORE billing — and before
    # the mode branches — so a refused asset never reaches the gate,
    # never leaves a reservation, and is refused the same way in both
    # modes. Raises FidelityLockError / KeyError.
    composite.validate_foreground(store, asset)
    foreground_record = store.get_record(asset)

    def _error(code: str, message: str, **extra) -> dict:
        return {
            "status": "error",
            "tool": "draw",
            "asset": asset,
            "scene_prompt": scene_prompt,
            "output_asset": None,
            "fidelity_receipt": None,
            "model": DRAW_BACKGROUND_MODEL,
            "error": {"code": code, "message": message, **extra},
        }

    if config.use_placeholder_plate():
        return _draw_with_placeholder_plate(store, asset, scene_prompt)

    try:
        meta_client.require_meta_api_key()
    except meta_client.NotConfiguredError as exc:
        return _error("NOT_CONFIGURED", str(exc))

    projected = meta_client.project_draw_cost_usd(DRAW_BACKGROUND_MODEL)
    try:
        plate_handle, billing = meta_client.generate_background_plate(
            scene_prompt,
            foreground_record.width,
            foreground_record.height,
            model=DRAW_BACKGROUND_MODEL,
        )
    except meta_client.ImageResultError as exc:
        return _error(exc.code, str(exc), cost_counted_usd=projected)

    handle, receipt = composite.draw_product(
        store, asset, scene_prompt, plate_handle=plate_handle
    )
    if receipt["changed_opaque_pixels"] != 0:
        # The Lock is measured, not assumed: a composite that changed
        # opaque product pixels must not ship under a fidelity receipt
        # claiming otherwise. The composite stays stored for inspection
        # (its handle rides in the error), but the tool reports failure.
        return _error(
            "FIDELITY_VIOLATION",
            "The compositor measured "
            f"{receipt['changed_opaque_pixels']} changed opaque "
            "foreground pixels; refusing to present this composite "
            "under the Fidelity Lock.",
            output_asset=handle,
            fidelity_receipt=receipt,
            cost_usd=billing["actual_usd"],
        )

    result = {
        "status": "ok",
        "tool": "draw",
        "asset": asset,
        "scene_prompt": scene_prompt,
        "output_asset": handle,
        "plate_asset": plate_handle,
        "fidelity_receipt": receipt,
        "model": DRAW_BACKGROUND_MODEL,
        "cost_usd": billing["actual_usd"],
        "usage": billing["usage"],
        "call_id": billing["call_id"],
        "note": (
            "Background plate generated by muse-image-1.0 and fitted to "
            "the product by deterministic code; the stored product layer "
            "was composited untouched and never sent to the image model."
        ),
    }
    preview = Image(data=store.read_bytes(handle), format="png")
    return [result, preview]


def _draw_with_placeholder_plate(store: AssetStore, asset: str, scene_prompt: str) -> list:
    """draw's offline dev mode (AGENTHAND_DRAW_PLACEHOLDER_PLATE=1).

    The full Fidelity Lock pipeline (validation, compositing, receipt)
    runs locally with the deterministic placeholder plate; the $0 pass
    through the choke point keeps the gate exercised in tests. Live
    mode never reaches this path implicitly: it is behind the explicit
    flag so a missing key or a failed image call can never degrade
    into a placeholder plate unnoticed.
    """
    outcome: dict = {}

    def _run_composite() -> dict:
        handle, receipt = composite.draw_product(store, asset, scene_prompt)
        outcome["handle"] = handle
        outcome["receipt"] = receipt
        return {}  # no model usage: the plate is a local placeholder

    billing = meta_client.billed_call(
        "draw",
        DRAW_BACKGROUND_MODEL,
        0.0,
        _run_composite,
        status="stub",
        note="Local placeholder plate (dev flag AGENTHAND_DRAW_PLACEHOLDER_PLATE); no API call.",
    )
    result = {
        "status": "ok",
        "tool": "draw",
        "asset": asset,
        "scene_prompt": scene_prompt,
        "output_asset": outcome["handle"],
        "plate_asset": None,
        "fidelity_receipt": outcome["receipt"],
        "model": DRAW_BACKGROUND_MODEL,
        "cost_usd": billing["actual_usd"],
        "note": (
            "OFFLINE DEV MODE (AGENTHAND_DRAW_PLACEHOLDER_PLATE): the "
            "plate is a deterministic local placeholder, not a generated "
            "scene; no API call was made. The compositing, lineage "
            "checks, and fidelity receipt are the real pipeline."
        ),
    }
    preview = Image(data=store.read_bytes(outcome["handle"]), format="png")
    return [result, preview]


@mcp.tool()
def cut_out(image: str, concept: str | None = None) -> dict:
    """Cut the product out of its photo as a transparent PNG.

    Args:
        image: The product photo — an asset handle (asset://<id>), an
            http(s) URL, or a base64 data URI. It is ingested and
            normalized first.
        concept: Optional noun-phrase concept naming what to segment
            ("brown leather wallet"). When omitted, the identify planning
            step runs internally to produce the concept and alternates.

    Calls SAM 3.1 with the concept phrase and decodes the returned mask
    (Meta's official parser, behind the sam_masks boundary). The mask
    is quality-checked — coverage sane (not empty, not ~the whole
    frame) and dominated by one connected region — and on a zero-match
    or a poor mask the loop retries ONCE with the first alternate
    phrase; every attempt is traced in the result. The foreground is
    the source pixels through the accepted mask, nothing regenerated;
    foreground and mask are stored with their hashes and lineage to the
    source photo.

    Failures return a structured error: NOT_CONFIGURED (no META_API_KEY;
    checked before billing, so no ledger write), NO_MATCH / POOR_MASK
    (no usable mask after the bounded attempts; the attempts' spend
    stays counted), BAD_MODEL_RESPONSE (SAM output unusable; spend
    counted). A planning failure inside the chain (concept omitted and
    identify failed) surfaces as that step's error code with
    plan_error attached.
    """
    store = _store()
    handle = ingest.ingest(image, store)
    source_record = store.get_record(handle)
    store.verify_integrity(handle)
    source_image = store.read_image(handle)

    concept_source = "provided"
    alternates: list[str] = []
    plan_error = None
    if concept is None:
        plan = _plan_cut(store, handle)
        concept = plan["concept"]
        alternates = plan["alternates"]
        plan_error = plan.get("error")
        concept_source = "identify_internal"

    def _error(code: str, message: str, **extra) -> dict:
        return {
            "status": "error",
            "tool": "cut_out",
            "image": handle,
            "concept": concept,
            "concept_source": concept_source,
            "alternates": alternates,
            "plan_error": plan_error,
            "output_asset": None,
            "mask_asset": None,
            "model": CUT_OUT_MODEL,
            "error": {"code": code, "message": message, **extra},
        }

    if concept is None:
        # The planning step produced no phrase to segment with (its own
        # error, e.g. NOT_CONFIGURED, rides in plan_error). No SAM call
        # is possible and none is billed.
        code = (plan_error or {}).get("code", "NO_CONCEPT")
        return _error(
            code,
            "No segmentation concept available: the identify planning "
            "step did not produce one.",
        )

    try:
        meta_client.require_meta_api_key()
    except meta_client.NotConfiguredError as exc:
        return _error("NOT_CONFIGURED", str(exc))

    # The attempt loop is bounded: the concept, plus one recovery retry
    # with the first alternate. The reservation prices exactly the
    # attempts the loop may make.
    phrases = [concept, *alternates[: meta_client.SAM_MAX_ATTEMPTS - 1]]
    projected = meta_client.project_cut_out_cost_usd(CUT_OUT_MODEL, len(phrases))
    outcome: dict = {}

    def _run_attempts() -> dict:
        result = segmentation.run_attempts(
            store.read_bytes(handle),
            phrases,
            model=CUT_OUT_MODEL,
            frame_width=source_image.width,
            frame_height=source_image.height,
        )
        outcome.update(result)
        return result["usage"]

    try:
        billing = meta_client.billed_call(
            "cut_out", CUT_OUT_MODEL, projected, _run_attempts
        )
    except segmentation.CutOutResultError as exc:
        return _error(
            exc.code,
            str(exc),
            attempts=exc.attempts,
            cost_counted_usd=projected,
        )

    mask_buffer = BytesIO()
    outcome["mask_image"].save(mask_buffer, format="PNG")
    mask_handle = store.put_bytes(
        mask_buffer.getvalue(),
        kind=KIND_MASK,
        suffix=".png",
        source_asset_id=source_record.asset_id,
    )
    foreground = segmentation.extract_foreground(source_image, outcome["mask_image"])
    foreground_handle = store.put_image(
        foreground,
        kind=KIND_FOREGROUND,
        source_asset_id=source_record.asset_id,
    )
    foreground_record = store.get_record(foreground_handle)
    mask_record = store.get_record(mask_handle)

    return {
        "status": "ok",
        "tool": "cut_out",
        "image": handle,
        "concept": outcome["phrase"],
        "requested_concept": concept,
        "concept_source": concept_source,
        "alternates": alternates,
        "plan_error": plan_error,
        "output_asset": foreground_handle,
        "mask_asset": mask_handle,
        "hashes": {
            "source": {
                "sha256": source_record.sha256,
                "pixel_sha256": source_record.pixel_sha256,
            },
            "foreground": {
                "sha256": foreground_record.sha256,
                "pixel_sha256": foreground_record.pixel_sha256,
            },
            "mask": {
                "sha256": mask_record.sha256,
                "pixel_sha256": mask_record.pixel_sha256,
            },
        },
        "attempts": outcome["attempts"],
        "model": CUT_OUT_MODEL,
        "cost_usd": billing["actual_usd"],
        "usage": billing["usage"],
        "call_id": billing["call_id"],
    }


def _run_identify(store: AssetStore, handle: str) -> dict:
    """Run the real identify planning step for a stored photo.

    On success returns the plan (description, concept, alternates,
    listing fields) plus cost_usd, usage, and call_id from the settled
    receipt. Expected failures return {"error": {...}} instead of
    raising:

    - NOT_CONFIGURED: no META_API_KEY. Checked before billed_call runs,
      so nothing is written to the ledger for a setup problem.
    - BAD_MODEL_RESPONSE: the model's response was unusable. The call
      went through the choke point and its reservation stays counted as
      spend; cost_counted_usd reports the reserved amount. When the body
      was unparseable, its full raw text was saved under data/debug/
      and debug_path points at that file.

    SpendCapExceeded propagates: an exhausted budget refuses loudly
    rather than degrading into an empty plan.
    """
    try:
        meta_client.require_meta_api_key()
    except meta_client.NotConfiguredError as exc:
        return {"error": {"code": "NOT_CONFIGURED", "message": str(exc)}}

    record = store.get_record(handle)
    store.verify_integrity(handle)
    png_bytes = store.read_bytes(handle)
    projected = meta_client.project_identify_cost_usd(
        IDENTIFY_MODEL, record.width, record.height
    )
    outcome: dict = {}

    def _call() -> dict:
        plan, usage = meta_client.vision_identify(png_bytes, model=IDENTIFY_MODEL)
        outcome["plan"] = plan
        return usage

    try:
        billing = meta_client.billed_call(
            "identify", IDENTIFY_MODEL, projected, _call
        )
    except meta_client.IdentifyResultError as exc:
        error = {
            "code": "BAD_MODEL_RESPONSE",
            "message": str(exc),
            "cost_counted_usd": projected,
        }
        if getattr(exc, "debug_path", None):
            error["debug_path"] = exc.debug_path
        return {"error": error}
    plan = dict(outcome["plan"])
    plan["model"] = IDENTIFY_MODEL
    plan["cost_usd"] = billing["actual_usd"]
    plan["usage"] = billing["usage"]
    plan["call_id"] = billing["call_id"]
    return plan


def _plan_cut(store: AssetStore, handle: str) -> dict:
    """The identify planning step, as shared internal logic.

    cut_out calls this when no concept is supplied, so the plan is
    produced inside the chain instead of by a separate tool call. An
    expected identify failure (not configured, unusable response)
    degrades to an empty plan with the error attached: cut_out's own
    segmentation step is still stubbed, so the chain reports the
    planning gap in its result instead of crashing.
    """
    result = _run_identify(store, handle)
    if "error" in result:
        return {
            "description": None,
            "concept": None,
            "alternates": [],
            "model": IDENTIFY_MODEL,
            "error": result["error"],
        }
    return result


@mcp.tool()
def identify(image: str) -> dict:
    """Plan the cut for a product photo (step inside the listing chain).

    Args:
        image: The product photo — an asset handle (asset://<id>), an
            http(s) URL, or a base64 data URI. It is ingested and
            normalized first.

    Reads the photo with the vision model and returns the plan the
    chain consumes: a structured description, the noun-phrase concept
    suitable for text-prompted segmentation ("brown leather wallet")
    with at least two alternate phrasings the mask-recovery loop can
    retry with, plus listing copy (suggested_title, listing_bullets,
    condition_notes). The call is billed through the spend-cap choke
    point and the result carries its actual cost and token usage.

    Without META_API_KEY configured the tool returns a structured
    NOT_CONFIGURED error and makes no call (and no ledger entry). This
    tool exists to serve the chain; the sellable outputs are cut_out's
    transparent PNG and draw's staged composite with its fidelity
    receipt.
    """
    store = _store()
    handle = ingest.ingest(image, store)
    result = _run_identify(store, handle)
    if "error" in result:
        return {
            "status": "error",
            "tool": "identify",
            "image": handle,
            "description": None,
            "concept": None,
            "alternates": [],
            "suggested_title": None,
            "listing_bullets": [],
            "condition_notes": None,
            "model": IDENTIFY_MODEL,
            "error": result["error"],
        }
    return {
        "status": "ok",
        "tool": "identify",
        "image": handle,
        "description": result["description"],
        "concept": result["concept"],
        "alternates": result["alternates"],
        "suggested_title": result["suggested_title"],
        "listing_bullets": result["listing_bullets"],
        "condition_notes": result["condition_notes"],
        "model": IDENTIFY_MODEL,
        "cost_usd": result["cost_usd"],
        "usage": result["usage"],
        "call_id": result["call_id"],
    }


def main() -> None:
    # Make sure the data dir exists so the first receipt write cannot fail
    # on a missing directory; the store and ledger create their own files.
    store = AssetStore(config.get_data_dir())
    store.assets_dir.mkdir(parents=True, exist_ok=True)
    mcp.run(transport="stdio")


if __name__ == "__main__":
    main()
