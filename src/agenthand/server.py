"""agenthand MCP server (stdio transport).

Three tools for AI agents that help people sell:

  identify(image)            -> what is this product, and how would you ask
                                a segmentation model for it?
  cut_out(image, concept)    -> the product, cut out, as a transparent PNG
  draw(asset, scene_prompt)  -> the REAL product placed into a generated
                                scene, under the Fidelity Lock

FIDELITY LOCK (the core design invariant of draw):
  The product layer is NEVER regenerated by a model. Segmentation extracts
  the real foreground; that layer is stored untouched and its sha256 is
  recorded in the asset store. The image model generates ONLY the
  background scene plate. Deterministic code composites the stored product
  layer onto the plate. The returned fidelity receipt carries the source,
  foreground, and mask hashes plus the count of changed foreground pixels,
  so a caller can verify the product it got is the product that was
  photographed. Any change to this module must preserve that invariant:
  if a code path regenerates product pixels with a model, it is a bug,
  not a feature.

All three tools are currently STUBBED: they exercise the plumbing (asset
handles, cost receipts, the fail-closed spend cap) and return structured
"not yet wired" results. No external API calls are made anywhere in this
file yet. When a tool is wired, its billable call must go through
_gate_billable_call() first, unchanged.
"""

from __future__ import annotations

from mcp.server.mcpserver import MCPServer

from . import config, ledger, pricing
from .assets import AssetStore

# mcp Python SDK v2: the high-level server class is MCPServer
# (renamed from FastMCP in v1).
mcp = MCPServer("agenthand")

# Model assignments (priced in pricing.py). identify starts on Spark; a
# Spark-vs-Wonder A/B during the build decides whether it stays there.
IDENTIFY_MODEL = "muse-spark-1.3"
CUT_OUT_MODEL = "sam-3.1"
DRAW_BACKGROUND_MODEL = "muse-image-1.0"

STUB_NOTE = "Stub: model not wired yet; no external call was made."


def _gate_billable_call(projected_usd: float) -> None:
    """Fail-closed spend gate. Every billable call passes through here first.

    Reads the ledger total and refuses (SpendCapExceeded) if this call would
    push total spend past the configured cap. Stub calls project $0.00, so
    they pass unless the ledger is already at or over the cap, which is the
    correct behavior: an exhausted budget refuses even no-op work rather
    than letting callers probe around the cap.
    """
    ledger.check_spend_cap(
        config.get_ledger_path(), projected_usd, config.get_total_spend_cap_usd()
    )


def _record_receipt(
    tool: str, model: str | None, status: str, note: str = "", **usage
) -> float:
    """Price a call from the pricing table and append its receipt."""
    usd = pricing.estimate_cost_usd(model, **usage) if model else 0.0
    ledger.append_receipt(
        config.get_ledger_path(),
        ledger.Receipt(tool=tool, model=model, usd_estimate=usd, status=status, note=note),
    )
    return usd


@mcp.tool()
def identify(image: str) -> dict:
    """Identify the product in a photo.

    Args:
        image: Asset handle (asset://<id>) of the product photo.

    Returns a structured description of the product plus a noun-phrase
    concept suitable for text-prompted segmentation ("brown leather
    wallet"), with alternate phrasings the cut_out mask-recovery loop can
    retry with when the first mask is poor.
    """
    _gate_billable_call(0.0)
    _record_receipt("identify", IDENTIFY_MODEL, status="stub", note=STUB_NOTE)
    return {
        "status": "not_yet_wired",
        "tool": "identify",
        "image": image,
        "description": None,
        "concept": None,
        "alternates": [],
        "model": IDENTIFY_MODEL,
        "note": STUB_NOTE,
    }


@mcp.tool()
def cut_out(image: str, concept: str) -> dict:
    """Cut the product out of its photo as a transparent PNG.

    Args:
        image: Asset handle (asset://<id>) of the product photo.
        concept: Noun-phrase concept from identify, naming what to segment.

    Wired behavior: the segmentation model returns a mask for the concept;
    the mask is quality-checked (a bounded recovery loop retries once with
    an alternate concept phrase on a poor mask, traced in the receipt); the
    extracted foreground is stored untouched in the asset store with its
    sha256 recorded, and the new asset handle is returned.
    """
    _gate_billable_call(0.0)
    _record_receipt("cut_out", CUT_OUT_MODEL, status="stub", note=STUB_NOTE)
    return {
        "status": "not_yet_wired",
        "tool": "cut_out",
        "image": image,
        "concept": concept,
        "output_asset": None,
        "mask_asset": None,
        "model": CUT_OUT_MODEL,
        "note": STUB_NOTE,
    }


@mcp.tool()
def draw(asset: str, scene_prompt: str) -> dict:
    """Place the real product into a generated scene. Fidelity Lock applies.

    Args:
        asset: Asset handle (asset://<id>) of the cut-out product layer
            produced by cut_out.
        scene_prompt: Description of the scene to generate around the
            product, e.g. "a regal, warmly lit reading room".

    The product layer referenced by `asset` is composited onto the
    generated background plate exactly as stored; it is never regenerated,
    restyled, or "improved" by a model. The wired tool returns a fidelity
    receipt (source/foreground/mask hashes, transformations applied,
    changed foreground pixel count, model calls, cost) alongside the
    composite's asset handle.
    """
    _gate_billable_call(0.0)
    _record_receipt("draw", DRAW_BACKGROUND_MODEL, status="stub", note=STUB_NOTE)
    return {
        "status": "not_yet_wired",
        "tool": "draw",
        "asset": asset,
        "scene_prompt": scene_prompt,
        "output_asset": None,
        "fidelity_receipt": None,
        "model": DRAW_BACKGROUND_MODEL,
        "note": STUB_NOTE,
    }


def main() -> None:
    # Make sure the data dir exists so the first receipt write cannot fail
    # on a missing directory; the store and ledger create their own files.
    store = AssetStore(config.get_data_dir())
    store.assets_dir.mkdir(parents=True, exist_ok=True)
    mcp.run(transport="stdio")


if __name__ == "__main__":
    main()
