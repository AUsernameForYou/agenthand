"""The Fidelity Lock engine: deterministic compositing, no models.

The invariant, enforced here in code (not just promised in docs):

- The product layer is the stored foreground asset, loaded byte-for-byte
  and pixel-for-pixel from the asset store after an integrity check. It is
  NEVER scaled, re-encoded through a model, or regenerated.
- The background plate is the only generated element. When a real image
  model is wired in, it produces the plate; the plate function takes ONLY
  a prompt and dimensions, so product pixels cannot reach the generator.
- The plate is resized/cropped to the product's dimensions — never the
  reverse — and deterministic alpha compositing places the product layer
  over it.
- The receipt measures the result: pixels where the foreground alpha is
  fully opaque must be identical between the stored foreground and the
  composite (count reported, and it must be 0 for the claim to hold);
  edge-band pixels (0 < alpha < 255) blend by design and are counted
  separately.

The plate itself comes from one of two places: a background_plate
asset generated by muse-image-1.0 through the billing choke point
(meta_client.generate_background_plate), or — only when the server
runs with the offline dev flag — the deterministic local placeholder
below, derived from the prompt, so the pipeline remains testable
offline with zero API calls.
"""

from __future__ import annotations

import hashlib
from io import BytesIO

import cv2
import numpy as np
from PIL import Image, ImageOps

from .assets import (
    HANDLE_PREFIX,
    KIND_COMPOSITE,
    KIND_FOREGROUND,
    KIND_MASK,
    KIND_PLATE,
    KIND_SOURCE,
    AssetIntegrityError,
    AssetRecord,
    AssetStore,
    carry_color_profile,
    color_profile_sha256_of_image,
    describe_color_profile,
    icc_profile_of_image,
    pixel_hash_of_image,
)

# A foreground pixel counts as product only at exactly this alpha. The
# threshold is named in every receipt so the claim's terms are pinned,
# not implied.
OPAQUE_ALPHA_THRESHOLD = 255


class FidelityLockError(RuntimeError):
    """Raised when an asset cannot be composited under the Fidelity Lock."""


def generate_background_plate(prompt: str, width: int, height: int) -> Image.Image:
    """Produce a background plate from a prompt and dimensions ONLY.

    This signature is the Fidelity Lock contract for background
    generation: no product bytes, no product handle, no product pixels can
    be passed in, so the generator cannot touch the product layer. When
    muse-image-1.0 is wired, this function is where its output lands.

    Until then it returns a deterministic placeholder: a vertical
    gradient whose colors derive from the prompt hash. Same prompt, same
    plate, no API call.
    """
    digest = hashlib.sha256(prompt.encode("utf-8")).digest()
    top = tuple(digest[0:3])
    bottom = tuple(digest[3:6])
    plate = Image.new("RGBA", (width, height))
    for y in range(height):
        t = y / max(height - 1, 1)
        color = tuple(int(top[i] + (bottom[i] - top[i]) * t) for i in range(3)) + (255,)
        plate.paste(color, (0, y, width, y + 1))
    return plate


def _fit_plate(plate: Image.Image, size: tuple[int, int]) -> tuple[Image.Image, list[str]]:
    """Resize/crop the PLATE to the product's dimensions. Never the reverse."""
    if plate.size == size:
        return plate, []
    fitted = ImageOps.fit(plate, size)
    return fitted, [f"plate_resized_and_center_cropped_to_{size[0]}x{size[1]}"]


def _distance_to_class(
    alpha: bytes, width: int, height: int, target
) -> np.ndarray:
    """Manhattan distance from every pixel to the nearest target pixel.

    Returns a (height, width) int64 array. Computed with OpenCV's L1
    distance transform, which is exact for the Manhattan metric —
    validated value-for-value against the two-pass chamfer loop it
    replaced, over randomized rasters including the border cases
    below. When NO pixel matches the target (a mask with no fully
    opaque pixel, say), distance is measured to the image border
    instead, so callers still get a finite field.
    """
    values = np.frombuffer(alpha, dtype=np.uint8).reshape(height, width)
    mask = target(values)
    if not mask.any():
        xs = np.arange(width)
        ys = np.arange(height)
        return np.minimum(
            np.minimum(xs + 1, width - xs)[np.newaxis, :],
            np.minimum(ys + 1, height - ys)[:, np.newaxis],
        )
    src = np.where(mask, 0, 255).astype(np.uint8)
    return cv2.distanceTransform(src, cv2.DIST_L1, 3).astype(np.int64)


def _edge_band_max_width(alpha: bytes, width: int, height: int) -> int:
    """The edge band's maximum width in pixels.

    Defined as the longest shortest path through band pixels from the
    fully opaque region to the fully transparent region: for a
    straight feather of thickness t, every crossing path has length t.
    (A run-length measure would confuse the band's width with its
    length along the product's edge; a distance-to-nearest measure
    alone reports the band's radius, half its width.)

    The edge band is where a soft mask blends the product into the
    plate; if most of the product hid there, "0 changed" would cover a
    shrunken pixel set (the J2 Gauntlet's soft-mask attack). The width
    is measured and receipted so the band's size is a checkable fact,
    not a footnote.
    """
    if width == 0 or height == 0:
        return 0
    values = np.frombuffer(alpha, dtype=np.uint8)
    band = (values > 0) & (values < 255)
    if not band.any():
        return 0
    to_opaque = _distance_to_class(alpha, width, height, lambda a: a == 255)
    to_transparent = _distance_to_class(alpha, width, height, lambda a: a == 0)
    crossing = (to_opaque + to_transparent - 1).ravel()
    return int(crossing[band].max())


def _measure(foreground: Image.Image, composite: Image.Image) -> dict:
    """Count opaque / edge-band / transparent pixels and verify the lock.

    A foreground pixel with alpha 255 must appear in the composite
    byte-identical; the count of violations is measured, not assumed.
    Also measures the mask's total footprint, the opaque share of it,
    and the edge band's maximum width, so a receipt cannot quietly
    shrink the set of pixels the "0 changed" claim covers.
    """
    fg_pixels = np.frombuffer(foreground.tobytes(), dtype=np.uint8).reshape(-1, 4)
    out_pixels = np.frombuffer(composite.tobytes(), dtype=np.uint8).reshape(-1, 4)
    alpha = np.frombuffer(foreground.getchannel("A").tobytes(), dtype=np.uint8)
    opaque_mask = alpha == OPAQUE_ALPHA_THRESHOLD
    opaque = int(np.count_nonzero(opaque_mask))
    edge_band = int(np.count_nonzero((alpha > 0) & ~opaque_mask))
    transparent = int(np.count_nonzero(alpha == 0))
    changed_opaque = int(
        np.count_nonzero(np.any(fg_pixels != out_pixels, axis=1) & opaque_mask)
    )
    mask_total = opaque + edge_band
    return {
        "opaque_pixels": opaque,
        "edge_band_pixels": edge_band,
        "transparent_pixels": transparent,
        "changed_opaque_pixels": changed_opaque,
        "mask_pixels_total": mask_total,
        "opaque_fraction": round(opaque / mask_total, 6) if mask_total else 0.0,
        "edge_band_max_width_px": _edge_band_max_width(
            alpha, foreground.width, foreground.height
        ),
    }


def composite_images(
    foreground: Image.Image, plate: Image.Image
) -> tuple[Image.Image, dict, list[str]]:
    """Composite a foreground over a plate; returns (image, counts, transforms)."""
    fg = foreground.convert("RGBA")
    fitted, transformations = _fit_plate(plate.convert("RGBA"), fg.size)
    out = Image.alpha_composite(fitted, fg)
    # alpha_composite drops the foreground's ICC profile; the composite
    # must carry the product's colour profile, not the plate's silence.
    carry_color_profile(fg, out)
    return out, _measure(fg, out), transformations


def validate_foreground(store: AssetStore, foreground_handle: str) -> list[AssetRecord]:
    """Check an asset may be composited; returns its lineage chain.

    Raises FidelityLockError (or KeyError for an unknown handle) unless
    the asset is a foreground_png whose lineage ends at a source_photo
    and the stored bytes of both match their recorded hashes.
    """
    record = store.get_record(foreground_handle)
    if record.kind != KIND_FOREGROUND:
        raise FidelityLockError(
            f"draw requires a {KIND_FOREGROUND} asset (the cut-out product "
            f"layer); {foreground_handle!r} is kind {record.kind!r}. "
            "Compositing anything else would break the Fidelity Lock."
        )
    chain = store.lineage(foreground_handle)
    source_record = chain[-1]
    if source_record.kind != KIND_SOURCE:
        raise FidelityLockError(
            f"Foreground {foreground_handle!r} traces back to kind "
            f"{source_record.kind!r}, not a {KIND_SOURCE}. Its provenance "
            "cannot be verified, so it cannot be composited."
        )
    # The stored bytes must be exactly what was recorded. Raises on mismatch.
    store.verify_integrity(foreground_handle)
    if source_record.asset_id != record.asset_id:
        store.verify_integrity(HANDLE_PREFIX + source_record.asset_id)
    return chain


def draw_product(
    store: AssetStore,
    foreground_handle: str,
    scene_prompt: str,
    *,
    plate_handle: str | None = None,
) -> tuple[str, dict]:
    """Composite a stored foreground into a scene; returns (handle, receipt).

    Enforces the Fidelity Lock before any pixels move: the asset must be
    a foreground_png, its lineage must end at a source_photo, and the
    stored bytes must match their recorded hashes.
    """
    chain = validate_foreground(store, foreground_handle)
    record = chain[0]
    source_record = chain[-1]

    foreground = store.read_image(foreground_handle)

    mask_record = next((r for r in chain if r.kind == KIND_MASK), None)
    if mask_record is not None:
        mask_asset = HANDLE_PREFIX + mask_record.asset_id
        mask_sha256 = mask_record.sha256
        mask_pixel_sha256 = mask_record.pixel_sha256
        mask_source = "asset"
    else:
        # No separate mask asset in the chain: the foreground's own alpha
        # channel is the mask. Hash the derived mask so the receipt still
        # pins exactly which mask the composite used.
        mask_image = foreground.getchannel("A")
        buffer = BytesIO()
        mask_image.save(buffer, format="PNG")
        mask_asset = None
        mask_sha256 = hashlib.sha256(buffer.getvalue()).hexdigest()
        mask_pixel_sha256 = pixel_hash_of_image(mask_image)
        mask_source = "foreground_alpha"

    if plate_handle is not None:
        plate_record = store.get_record(plate_handle)
        if plate_record.kind != KIND_PLATE:
            raise FidelityLockError(
                f"Background plate {plate_handle!r} is kind "
                f"{plate_record.kind!r}, not {KIND_PLATE}."
            )
        plate = store.read_image(plate_handle)
        plate_source = "asset"
        plate_asset = plate_handle
        plate_sha256 = plate_record.sha256
        plate_pixel_sha256 = plate_record.pixel_sha256
    else:
        plate = generate_background_plate(
            scene_prompt, foreground.width, foreground.height
        )
        plate_source = "local_placeholder"
        plate_asset = None
        plate_sha256 = None
        plate_pixel_sha256 = None

    composite, _in_memory_counts, transformations = composite_images(foreground, plate)
    composite_handle = store.put_image(
        composite, kind=KIND_COMPOSITE, source_asset_id=record.asset_id
    )
    composite_record = store.get_record(composite_handle)

    # The receipt's counts are measured on the DELIVERED FILE, decoded
    # back from the store — not on the in-memory buffer that produced
    # it (the J2 Gauntlet: "the count runs on the in-memory buffer, the
    # film shows the file"). A later re-encode or cast that changed
    # pixels would show up here, and the independent verifier
    # (verify_receipt_from_disk) recounts the same files the same way.
    counts = _measure(
        store.read_image(foreground_handle), store.read_image(composite_handle)
    )

    # Colour-profile identity, source photo vs delivered composite.
    # Pixel hashes cannot see a profile change (identical values,
    # different displayed colours), so the receipt pins the profile
    # hashes and states preservation as its own checkable fact.
    color_profile_preserved = (
        source_record.color_profile_sha256 == composite_record.color_profile_sha256
    )

    receipt = {
        "source_asset": HANDLE_PREFIX + source_record.asset_id,
        "source_sha256": source_record.sha256,
        "source_pixel_sha256": source_record.pixel_sha256,
        "foreground_asset": foreground_handle,
        "foreground_sha256": record.sha256,
        "foreground_pixel_sha256": record.pixel_sha256,
        "mask_asset": mask_asset,
        "mask_sha256": mask_sha256,
        "mask_pixel_sha256": mask_pixel_sha256,
        "mask_source": mask_source,
        "changed_opaque_pixels": counts["changed_opaque_pixels"],
        "opaque_pixels": counts["opaque_pixels"],
        "edge_band_pixels": counts["edge_band_pixels"],
        "transparent_pixels": counts["transparent_pixels"],
        "mask_pixels_total": counts["mask_pixels_total"],
        "opaque_fraction": counts["opaque_fraction"],
        "edge_band_max_width_px": counts["edge_band_max_width_px"],
        "opaque_alpha_threshold": OPAQUE_ALPHA_THRESHOLD,
        "changed_predicate": (
            "a pixel counts as changed when its RGBA value in the "
            "composite differs at all from the stored foreground at a "
            "position where the foreground alpha equals "
            "opaque_alpha_threshold; edge-band pixels (0 < alpha < "
            "threshold) blend by design, are excluded from the count, "
            "and are published above as edge_band_pixels and "
            "edge_band_max_width_px"
        ),
        "pixel_tolerance": 0,
        "count_sample": "decoded_delivered_file",
        "output_asset": composite_handle,
        "output_sha256": composite_record.sha256,
        "output_pixel_sha256": composite_record.pixel_sha256,
        "output_format": "PNG",
        "color_space": describe_color_profile(icc_profile_of_image(composite)),
        "color_profile_source_sha256": source_record.color_profile_sha256,
        "color_profile_foreground_sha256": record.color_profile_sha256,
        "color_profile_output_sha256": composite_record.color_profile_sha256,
        "color_profile_preserved": color_profile_preserved,
        "transformations": transformations,
        "product_layer_scaled": False,
        "plate_source": plate_source,
        "plate_asset": plate_asset,
        "plate_sha256": plate_sha256,
        "plate_pixel_sha256": plate_pixel_sha256,
        "claim": (
            "The stored extracted foreground reached the composite "
            "unchanged: every fully opaque foreground pixel in the "
            "composite is identical to the stored foreground layer "
            "(foreground hashes above pin that layer). Edge-band pixels "
            "blend with the plate by design and are counted separately. "
            "The composite carries the source photo's colour profile "
            "unchanged (color_profile_preserved above); a profile "
            "change is a fidelity failure even when pixel values match."
        ),
    }
    # Persist the receipt beside the composite (architecture Gauntlet,
    # Fable + GPT "adopt now, as a file"): a receipt that exists only
    # in the tool's return value is gone if the client drops it, and
    # the verify-from-disk story is stronger when the claims being
    # re-graded live with the files they describe. The server enriches
    # this same file with the billed call's cost and attribution once
    # billing settles (see server.draw).
    store.save_receipt(composite_handle, receipt)
    return composite_handle, receipt


def verify_receipt_from_disk(
    store: AssetStore, composite_handle: str, receipt: dict | None = None
) -> dict:
    """Independently re-verify a draw receipt from the stored FILES.

    The receipt draw returns is computed by the compositor, in memory,
    at draw time — the J2 Gauntlet's "self-graded receipt" objection.
    This is the independent path: it re-reads the stored source,
    foreground, and composite files from disk, re-checks every file
    against its recorded hashes, decodes the pixels fresh, recounts
    the changed opaque pixels, and re-derives the colour-profile
    identities. Nothing is taken from the receipt except the claims
    being checked and the handles of the assets it names.

    The receipt may be omitted: draw persists it beside the composite
    (``<asset_id>.receipt.json`` in the asset store) and it is loaded
    from there, so a composite found in the store carries the claims
    to check with it. A receipt supplied by the caller takes
    precedence over the persisted one. Receipts persisted by the
    server carry extra billing fields (cost, call attribution); only
    the fidelity fields are read here. ValueError is raised when no
    receipt is supplied and none is persisted for the composite.

    Returns a report dict: ``ok`` (True only when every check passes),
    ``checks`` (per-check booleans), ``problems`` (human-readable
    failures), and ``recomputed`` (the from-disk measurements). A
    tampered stored file, a recount that disagrees with the receipt,
    or a colour profile that differs between the source photo and the
    delivered composite all make ``ok`` False — they never raise, so a
    caller (the standalone verifier, the film's on-camera check) gets
    the full list of what is wrong. KeyError propagates for an unknown
    composite handle.
    """
    if receipt is None:
        receipt = store.load_receipt(composite_handle)
        if receipt is None:
            raise ValueError(
                f"No receipt supplied and none persisted beside "
                f"{composite_handle!r}; there are no claims to verify."
            )
    checks: dict[str, bool] = {}
    problems: list[str] = []

    def check(name: str, ok: bool, detail: str = "") -> None:
        checks[name] = bool(ok)
        if not ok:
            problems.append(f"{name}: {detail}" if detail else name)

    composite_record = store.get_record(composite_handle)
    foreground_handle = receipt["foreground_asset"]
    source_handle = receipt["source_asset"]

    # 1. Every stored file must still match the hashes recorded for it
    #    (file bytes, decoded pixels, colour profile). This is the
    #    tripwire for a tampered output file.
    for label, handle in (
        ("source", source_handle),
        ("foreground", foreground_handle),
        ("composite", composite_handle),
    ):
        try:
            store.verify_integrity(handle)
            check(f"{label}_file_integrity", True)
        except (AssetIntegrityError, KeyError) as exc:
            check(f"{label}_file_integrity", False, str(exc))

    # 2. Decode the foreground and the delivered composite fresh from
    #    disk and recount — the receipt's numbers must reproduce.
    foreground = store.read_image(foreground_handle)
    composite_image = store.read_image(composite_handle)
    check(
        "foreground_pixel_hash",
        pixel_hash_of_image(foreground) == receipt["foreground_pixel_sha256"],
        "decoded foreground pixels do not match the receipt's pinned hash",
    )
    check(
        "composite_pixel_hash",
        pixel_hash_of_image(composite_image) == composite_record.pixel_sha256,
        "decoded composite pixels do not match the stored asset record",
    )
    recomputed: dict = {}
    if foreground.size != composite_image.size:
        check(
            "recount",
            False,
            f"foreground is {foreground.size}, composite is "
            f"{composite_image.size}; sizes must match exactly",
        )
    else:
        counts = _measure(foreground, composite_image)
        recomputed.update(counts)
        for field in (
            "changed_opaque_pixels",
            "opaque_pixels",
            "edge_band_pixels",
            "transparent_pixels",
            "mask_pixels_total",
            "edge_band_max_width_px",
        ):
            check(
                f"recount_{field}",
                counts[field] == receipt[field],
                f"receipt says {receipt[field]}, recount from disk "
                f"finds {counts[field]}",
            )
        check(
            "recount_opaque_fraction",
            abs(counts["opaque_fraction"] - receipt["opaque_fraction"]) < 1e-9,
            f"receipt says {receipt['opaque_fraction']}, recount from "
            f"disk finds {counts['opaque_fraction']}",
        )

    # 3. Colour-profile identity, re-derived from the files: the
    #    profile the receipt names must be the profile in the files,
    #    and source and output profiles must be identical.
    source_image = store.read_image(source_handle)
    source_profile = color_profile_sha256_of_image(source_image)
    output_profile = color_profile_sha256_of_image(composite_image)
    recomputed["color_profile_source_sha256"] = source_profile
    recomputed["color_profile_output_sha256"] = output_profile
    check(
        "color_profile_matches_receipt",
        source_profile == receipt["color_profile_source_sha256"]
        and output_profile == receipt["color_profile_output_sha256"],
        "profiles decoded from the files differ from the receipt's "
        "recorded profile hashes",
    )
    preserved = source_profile == output_profile
    recomputed["color_profile_preserved"] = preserved
    check(
        "color_profile_preserved",
        preserved and receipt["color_profile_preserved"] is True,
        "the delivered composite's colour profile differs from the "
        "source photo's; identical pixel values would display as "
        "different colours",
    )

    return {
        "ok": all(checks.values()),
        "checks": checks,
        "problems": problems,
        "recomputed": recomputed,
        "composite_asset": composite_handle,
        "foreground_asset": foreground_handle,
        "source_asset": source_handle,
    }
