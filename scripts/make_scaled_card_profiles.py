"""Generate scaled card profiles from the real AH-46 layout profile.

Writes tests/fixtures/scaled-card-profiles.json with three experimental
sizes derived from AH-46 by a single uniform scale, fit-inside the
target card and centred (the same fit the print sheet uses):

- AH-42   4.25 x 2.83 in  (a "mini" postcard, ~0.71x AH-46)
- AH-35   3.50 x 2.33 in  (business-card-ish, ~0.58x AH-46)
- AH-LTR 11.0 x 8.50 in   (AH-46 art x1.83 centred on a landscape
          letter sheet; the sheet itself is the card, no cutting)

Every length in the geometry scales by the same factor; every point
is scaled then offset by the centring margin. The output also carries
"test_furniture_mm": the synthetic scene renderer's simplified lockup
furniture (hand blob + wordmark bar, positions taken from
tests/test_measure.py's AH-46 render) under the same transform, so
test scenes for the new sizes carry the same interior ink.

Usage:
    python scripts/make_scaled_card_profiles.py [layout-profile.json]
"""

from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_PROFILE = (
    Path.home()
    / "workspace"
    / "meta-hackathon"
    / "scale-card"
    / "print"
    / "layout-profile.json"
)
OUT = REPO / "tests" / "fixtures" / "scaled-card-profiles.json"

IN = 25.4
TARGETS = {
    "AH-42": (4.25 * IN, 2.83 * IN),
    "AH-35": (3.50 * IN, 2.33 * IN),
    "AH-LTR": (11.0 * IN, 8.5 * IN),
}
# Simplified lockup furniture in AH-46 card coordinates (from
# tests/test_measure.py): hand blob and wordmark bar rectangles.
FURNITURE = {"hand": (52.0, 52.0, 84.0, 78.0), "wordmark": (38.0, 84.0, 102.0, 92.0)}


def scale_card(base: dict, card_id: str, target_w: float, target_h: float) -> dict:
    bw, bh = float(base["card_width_mm"]), float(base["card_height_mm"])
    s = min(target_w / bw, target_h / bh)
    ox, oy = (target_w - bw * s) / 2.0, (target_h - bh * s) / 2.0

    def pt(p):
        return [round(p[0] * s + ox, 3), round(p[1] * s + oy, 3)]

    def ln(v):
        return round(float(v) * s, 3)

    card = copy.deepcopy(base)
    card["card_id"] = card_id
    card["version"] = 1
    card["supersedes"] = (
        f"experimental scale of AH-46 x{s:.4f} fit-inside "
        f"{target_w:.2f} x {target_h:.2f} mm, centred; not a print profile"
    )
    card["card_width_mm"] = round(target_w, 3)
    card["card_height_mm"] = round(target_h, 3)
    card["uniform_scale_from_AH-46"] = round(s, 5)
    card["art_offset_mm"] = [round(ox, 3), round(oy, 3)]

    frame = card["bracket_frame"]
    frame["corner_vertices_centreline_mm"] = {
        k: pt(v) for k, v in frame["corner_vertices_centreline_mm"].items()
    }
    frame["stroke_width_mm"] = ln(frame["stroke_width_mm"])
    frame["arm_centreline_length_mm"] = ln(frame["arm_centreline_length_mm"])

    for tick in card["ticks"]:
        tick["centre_mm"] = pt(tick["centre_mm"])
        tick["cut_along_arm_mm"] = ln(tick["cut_along_arm_mm"])
        tick["cut_across_mm"] = ln(tick["cut_across_mm"])

    ring = card["ring"]
    ring["centre_mm"] = pt(ring["centre_mm"])
    ring["outer_radius_mm"] = ln(ring["outer_radius_mm"])
    ring["inner_radius_mm"] = ln(ring["inner_radius_mm"])

    img = card.get("image")
    if img:
        img["scale_mm_per_unit"] = round(float(img["scale_mm_per_unit"]) * s, 6)
        img["offset_x_mm"] = round(float(img["offset_x_mm"]) * s + ox, 3)
        img["offset_y_mm"] = round(float(img["offset_y_mm"]) * s + oy, 3)
        img["printed_width_mm"] = ln(img["printed_width_mm"])
        img["printed_height_mm"] = ln(img["printed_height_mm"])

    block = card.get("lockup_block_mm")
    if block:
        x, y = pt((block["x"], block["y"]))
        block["x"], block["y"] = x, y
        block["width"] = ln(block["width"])
        block["height"] = ln(block["height"])

    card["test_furniture_mm"] = {
        name: pt((x1, y1)) + pt((x2, y2))
        for name, (x1, y1, x2, y2) in FURNITURE.items()
    }
    return card


def main() -> int:
    profile_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PROFILE
    data = json.loads(profile_path.read_text(encoding="utf-8"))
    base = data["cards"]["AH-46"]
    out = {
        "profile": "agenthand scale card — experimental scaled sizes (test fixtures)",
        "note": (
            "Generated by scripts/make_scaled_card_profiles.py from the "
            "AH-46 entry of the print layout profile. Uniform scale, "
            "fit-inside and centred on the target card."
        ),
        "cards": {
            cid: scale_card(base, cid, w, h) for cid, (w, h) in TARGETS.items()
        },
    }
    OUT.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    for cid, card in out["cards"].items():
        print(
            f"{cid}: {card['card_width_mm']} x {card['card_height_mm']} mm, "
            f"scale {card['uniform_scale_from_AH-46']}, "
            f"offset {card['art_offset_mm']}"
        )
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
